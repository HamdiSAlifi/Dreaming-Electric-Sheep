# arithmetic Operators
## addition
print(f"{a} + {b} = {a+b}")
print()

## Subtraction
print(f"{a} - {b} = {a-b}")
print()

## Multiplication
print(f"{a} * {b} = {a*b}")
print()

## Division
print(f"{a} / {b} = {a/b}")
print()

## Floor Division
print(f"{a} // {b} = {a//b}")
print()

## Modulus
print(f"{a} % {b} = {a%b}")
print()

## Exponentiation
print(f"{a} ** {b} = {a**b}")
print()

