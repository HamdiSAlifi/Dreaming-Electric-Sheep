## Greater than
print(f"{a} > {b} = {a>b}")
print()

## Greater than or equal to
print(f"{a} >= {b} = {a>=b}")
print()

## Less than
print(f"{a} > {b} = {a<b}")
print()

## Less than or equal to
print(f"{a} >= {b} = {a<=b}")
